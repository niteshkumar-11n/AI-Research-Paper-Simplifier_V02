import {
  Box,
  Typography,
  Card,
  CardContent,
  Chip,
  Divider,
  Button,
  Skeleton,
  useTheme,
} from "@mui/material";
import {
  Visibility,
  Science,
  Key,
  Summarize,
  Hub as HubIcon,
  Download,
  InsertDriveFile,
  AccessTime,
} from "@mui/icons-material";
import KnowledgeGraph from "./KnowledgeGraph";

function SectionCard({ icon, title, items, color }) {
  const theme = useTheme();
  const isDark = theme.palette.mode === "dark";

  return (
    <Card
      sx={{
        border: `1px solid ${theme.palette.divider}`,
        background: isDark ? "rgba(26,26,46,0.5)" : "#FFF",
        height: "100%",
      }}
    >
      <CardContent sx={{ p: 3 }}>
        <Box sx={{ display: "flex", alignItems: "center", gap: 1.5, mb: 2 }}>
          <Box
            sx={{
              width: 40,
              height: 40,
              borderRadius: 2,
              display: "flex",
              alignItems: "center",
              justifyContent: "center",
              background: `${color}18`,
              color: color,
            }}
          >
            {icon}
          </Box>
          <Typography variant="h6" sx={{ fontWeight: 700, fontSize: "1.05rem" }}>
            {title}
          </Typography>
        </Box>
        <Box component="ul" sx={{ pl: 2.5, m: 0 }}>
          {items.map((item, i) => (
            <Box
              component="li"
              key={i}
              sx={{
                mb: 1.2,
                color: "text.secondary",
                lineHeight: 1.7,
                fontSize: "0.9rem",
                "&::marker": { color: color },
              }}
            >
              {item}
            </Box>
          ))}
        </Box>
      </CardContent>
    </Card>
  );
}

export default function ResultPanel({ result, loading }) {
  const theme = useTheme();
  const isDark = theme.palette.mode === "dark";

  if (loading) {
    return (
      <Box sx={{ p: 3 }}>
        {[1, 2, 3, 4].map((i) => (
          <Skeleton key={i} variant="rounded" height={120} sx={{ mb: 2, borderRadius: 3 }} />
        ))}
      </Box>
    );
  }

  if (!result) return null;

  const handleDownload = () => {
    const graphNodes = result.graph_data?.nodes || [];
    const graphEdges = result.graph_data?.edges || [];

    const report = `
INSIGHTDOCS AI - ANALYSIS REPORT
${"=".repeat(50)}

File: ${result.file_name}
Date: ${new Date(result.created_at).toLocaleString()}
Type: ${result.file_type?.toUpperCase()}

${"─".repeat(50)}
OVERVIEW
${"─".repeat(50)}
${result.overview?.map((b) => `• ${b}`).join("\n") || "N/A"}

${"─".repeat(50)}
METHODOLOGY
${"─".repeat(50)}
${result.methodology?.map((b) => `• ${b}`).join("\n") || "N/A"}

${"─".repeat(50)}
KEY POINTS
${"─".repeat(50)}
${result.key_points?.map((b) => `• ${b}`).join("\n") || "N/A"}

${"─".repeat(50)}
AI SUMMARY
${"─".repeat(50)}
${result.summary || "N/A"}

${"─".repeat(50)}
KNOWLEDGE GRAPH: ${result.graph_data?.title || ""}
${"─".repeat(50)}
Entities: ${graphNodes.map((n) => n.label).join(", ")}
Relationships:
${graphEdges.map((e) => {
  const src = graphNodes.find((n) => n.id === e.source)?.label || e.source;
  const tgt = graphNodes.find((n) => n.id === e.target)?.label || e.target;
  return `  ${src} → ${tgt} (${e.label})`;
}).join("\n")}

${"=".repeat(50)}
Generated by InsightDocs AI
    `.trim();

    const blob = new Blob([report], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${result.title || "analysis"}_report.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const hasGraphData = result.graph_data?.nodes?.length > 0;

  return (
    <Box sx={{ animation: "fadeIn 0.5s ease-out" }}>
      {/* Header */}
      <Box sx={{ display: "flex", alignItems: "center", flexWrap: "wrap", gap: 2, mb: 3 }}>
        <Box sx={{ display: "flex", alignItems: "center", gap: 1.5, flex: 1 }}>
          <InsertDriveFile sx={{ color: "primary.main" }} />
          <Box>
            <Typography variant="h5" sx={{ fontWeight: 700 }}>
              {result.title || result.file_name}
            </Typography>
            <Box sx={{ display: "flex", alignItems: "center", gap: 1.5, mt: 0.5 }}>
              <Chip
                label={result.file_type?.toUpperCase()}
                size="small"
                sx={{
                  fontWeight: 600,
                  fontSize: "0.72rem",
                  background: isDark ? "rgba(124,58,237,0.15)" : "rgba(124,58,237,0.08)",
                  color: "primary.main",
                }}
              />
              <Box sx={{ display: "flex", alignItems: "center", gap: 0.5 }}>
                <AccessTime sx={{ fontSize: 14, color: "text.secondary" }} />
                <Typography variant="caption" sx={{ color: "text.secondary" }}>
                  {new Date(result.created_at).toLocaleString()}
                </Typography>
              </Box>
            </Box>
          </Box>
        </Box>
        <Button
          variant="outlined"
          startIcon={<Download />}
          onClick={handleDownload}
          size="small"
        >
          Download Report
        </Button>
      </Box>

      <Divider sx={{ mb: 3 }} />

      {/* Analysis Sections */}
      <Box sx={{ display: "grid", gridTemplateColumns: { xs: "1fr", md: "1fr 1fr" }, gap: 2.5, mb: 3 }}>
        {result.overview?.length > 0 && (
          <SectionCard
            icon={<Visibility sx={{ fontSize: 20 }} />}
            title="Overview"
            items={result.overview}
            color="#7C3AED"
          />
        )}
        {result.methodology?.length > 0 && (
          <SectionCard
            icon={<Science sx={{ fontSize: 20 }} />}
            title="Methodology"
            items={result.methodology}
            color="#06B6D4"
          />
        )}
        {result.key_points?.length > 0 && (
          <SectionCard
            icon={<Key sx={{ fontSize: 20 }} />}
            title="Key Points"
            items={result.key_points}
            color="#10B981"
          />
        )}

        {/* AI Summary */}
        {result.summary && (
          <Card
            sx={{
              border: `1px solid ${theme.palette.divider}`,
              background: isDark ? "rgba(26,26,46,0.5)" : "#FFF",
              height: "100%",
            }}
          >
            <CardContent sx={{ p: 3 }}>
              <Box sx={{ display: "flex", alignItems: "center", gap: 1.5, mb: 2 }}>
                <Box
                  sx={{
                    width: 40,
                    height: 40,
                    borderRadius: 2,
                    display: "flex",
                    alignItems: "center",
                    justifyContent: "center",
                    background: "rgba(245,158,11,0.1)",
                    color: "#F59E0B",
                  }}
                >
                  <Summarize sx={{ fontSize: 20 }} />
                </Box>
                <Typography variant="h6" sx={{ fontWeight: 700, fontSize: "1.05rem" }}>
                  AI Summary
                </Typography>
              </Box>
              <Typography variant="body2" sx={{ color: "text.secondary", lineHeight: 1.8 }}>
                {result.summary}
              </Typography>
            </CardContent>
          </Card>
        )}
      </Box>

      {/* Knowledge Graph */}
      {hasGraphData && (
        <Card
          sx={{
            border: `1px solid ${theme.palette.divider}`,
            background: isDark ? "rgba(26,26,46,0.5)" : "#FFF",
          }}
        >
          <CardContent sx={{ p: 3 }}>
            <Box sx={{ display: "flex", alignItems: "center", gap: 1.5, mb: 2 }}>
              <Box
                sx={{
                  width: 40,
                  height: 40,
                  borderRadius: 2,
                  display: "flex",
                  alignItems: "center",
                  justifyContent: "center",
                  background: "rgba(236,72,153,0.1)",
                  color: "#EC4899",
                }}
              >
                <HubIcon sx={{ fontSize: 20 }} />
              </Box>
              <Box>
                <Typography variant="h6" sx={{ fontWeight: 700, fontSize: "1.05rem" }}>
                  {result.graph_data?.title || "Knowledge Graph"}
                </Typography>
                {result.graph_data?.description && (
                  <Typography variant="caption" sx={{ color: "text.secondary" }}>
                    {result.graph_data.description}
                  </Typography>
                )}
              </Box>
            </Box>

            <KnowledgeGraph graphData={result.graph_data} />
          </CardContent>
        </Card>
      )}
    </Box>
  );
}
